# Задача №5 Раздел: Получение элементов, ключей и значений словаря

# У вас есть словарь, описывающий настройки приложения:
# settings = {"lang": "ru", "theme": "dark", "volume": 75}
# Вам нужно:
# Получить список всех ключей этого словаря, сохранить его в переменную keys_list и вывести на экран.
# Получить список всех значений этого словаря, сохранить его в переменную values_list и вывести на экран.
# Для решения используйте соответствующие методы словаря.

settings = {"lang": "ru", "theme": "dark", "volume": 75}
keys_list = list(settings.keys())
values_list = list(settings.values())
print(keys_list)
print(values_list)


# Задача №6 Раздел: Проверка на наличие ключей и значений

# У вас есть словарь, хранящий коды стран:
# country_codes = {"RU": "Russia", "US": "United States", "FR": "France"}
# Вам нужно написать код, который проверяет:
# Есть ли в словаре country_codes ключ "DE" (Германия).
# Есть ли в словаре country_codes значение "France".
# Результат каждой проверки (True или False) сохраните в отдельные переменные и выведите их на экран в таком порядке:
# Сначала результат проверки ключа "DE".
# Затем результат проверки значения "France".
# Для проверок используйте оператор in.

country_codes = {"RU": "Russia", "US": "United States", "FR": "France"}
has_DE = "DE" in country_codes.keys()
has_France = "France" in country_codes.values()
print(has_DE)
print(has_France)