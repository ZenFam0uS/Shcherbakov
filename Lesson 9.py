# Задача 1 (Декораторы)
# Напиши функцию greet(), которая возвращает строку "Привет, друг!".
# Затем напиши декоратор add_smiles, который будет оборачивать результат функции в смайлики, делая его таким: "😊 Привет, друг! 😊".

# 1. Создаем сам декоратор (функцию, которая принимает другую функцию)
def add_smiles(func):
    # 2. Внутри создаем функцию-обертку
    def wrapper():
        # 3. Вызываем исходную функцию и получаем её результат
        original_result = func()
        # 4. Модифицируем результат
        new_result = f"😊 {original_result} 😊"
        # 5. Возвращаем модифицированный результат
        return new_result
    # 6. Возвращаем функцию-обертку
    return wrapper

# 7. Применяем декоратор к функции
@add_smiles
def greet():
    # 8. Функция возвращает строку, а не печатает её
    return "Привет, друг!"

# 9. Проверяем
print(greet())  # Выведет: 😊 Привет, друг! 😊

