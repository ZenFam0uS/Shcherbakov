# Задача 16 (Раздел: Декораторы)

# Ваша задача — понять принцип работы декоратора.
# Напишите простой декоратор с именем my_decorator. Внутри него должна быть функция-обертка wrapper(), которая:
# Перед вызовом декорируемой функции выводит (print) строку: "Функция вызвана".
# Вызывает декорируемую функцию.
# После вызова декорируемой функции выводит строку: "Вызов функции завершен".
# Примените этот декоратор к функции say_hello(), которая просто выводит строку "Привет!".
# Напишите код: объявление декоратора, применение его к функции say_hello и вызов say_hello().
# Постарайтесь сделать это, не используя синтаксический сахар @.
# То есть, явно присвойте say_hello = my_decorator(say_hello) после объявления исходной функции say_hello.

def my_decorator(func):
    def wrapper():
        print("Функция вызвана")
        func()
        print("Вызов функции завершен")
    return wrapper
@my_decorator
def say_hello():
    print("Привет!")
say_hello()