# Задача 10 (Декораторы)
# Напиши декоратор repeat_twice, который заставляет функцию, которую он декорирует, выполниться два раза подряд.
# Для простоты, функция (например, say_hi(), которая печатает "Hi!") не принимает аргументов.

# 1. Создаем декоратор
def repeat_twice(func):
    # 2. Создаем обертку, которая будет заменять оригинальную функцию
    def wrapper():
        # 3. Вызываем оригинальную функцию ПЕРВЫЙ раз
        func()
        # 4. Вызываем оригинальную функцию ВТОРОЙ раз
        func()
    # 5. Возвращаем обертку
    return wrapper

# 6. Применяем декоратор к функции
@repeat_twice
def say_hi():
    print("Hi!")

# 7. Проверяем
say_hi()

