# Задача 1

# Напиши программу, которая:
# Создаёт текстовый файл с именем numbers.txt.
# Записывает в этот файл пять строк, каждая из которых содержит одно целое число от 1 до 5 (т.е. в первой строке будет "1", во второй — "2" и т.д.).
# После записи закрывает файл, а затем открывает его снова для чтения.
# Читает все строки из файла, вычисляет их сумму и выводит полученную сумму на экран.

# Требование: Для записи и чтения используй обычные методы open() и close(), без контекстного менеджера with.

file = open("numbers.txt", "w", encoding="utf-8")

file.write("1\n")
file.write("2\n")
file.write("3\n")
file.write("4\n")
file.write("5")
file.close()

file2 = open("numbers.txt", "r", encoding="utf-8")
lines = file2.readlines()
file2.close()

total = 0
for line in lines:
    num = int(line.strip())
    total += num

print("Сумма чисел из файла:",total)


