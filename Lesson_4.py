# Задача 1 Раздел: Получение элементов списка

# Дан список:
# colors = ["red", "green", "blue", "yellow", "black"]
# Напиши программу, которая выведет в консоль первый и последний элементы этого списка, каждый с новой строки.

colors = ["red", "green", "blue", "yellow", "black"]
first_color = colors[0]
last_color = colors[-1]
print(first_color)
print(last_color)


# Задача 2 Раздел: Добавление элементов в список и их замена

# Дан список:
# numbers = [10, 20, 30, 40]
# Добавь в конец списка numbers число 50.
# После этого замени второй элемент списка (со значением 20) на число 25.
# В конце программы выведи измененный список numbers на экран.

numbers = [10, 20, 30, 40]
numbers.append(50)
numbers[1] = 25
print(numbers)


# Задача 3 Раздел: Добавление элементов в конкретное место списка

# Дан список:
# fruits = ["apple", "banana", "cherry"]
# Добавь фрукт "orange" в список fruits между "apple" и "banana" (то есть, чтобы он стал вторым элементом в списке).
# В конце программы выведи измененный список fruits на экран.

fruits = ["apple", "banana", "cherry"]
fruits.insert(1,"orange")
print(fruits)


# Задача 4 Раздел: Срезы списка

# Дан список:
# items = ['book', 'pen', 'pencil', 'ruler', 'eraser']
# Создай новый список с именем selected, который будет содержать элементы из списка items со второго по четвёртый (включительно, то есть индексы 1, 2, 3).
# В конце программы выведи список selected на экран.

items = ['book', 'pen', 'pencil', 'ruler', 'eraser']
selected = items[1:4]
print(selected)


# Задача 5 Раздел: Удаление элементов из списка и его очистка

# Дан список:
# tools = ["hammer", "screwdriver", "wrench", "pliers", "saw"]
# Удали из списка tools элемент с индексом 2 (третий по счету).
# После этого удали из списка элемент "pliers" по его значению.
# В конце программы выведи измененный список tools на экран.

tools = ["hammer", "screwdriver", "wrench", "pliers", "saw"]
del tools[2]
tools.remove("pliers")
print(tools)


# Задача 6 Раздел: Слияние списков

# Даны два списка:
# list_a = [1, 2, 3]
# list_b = [4, 5, 6]
# Создай новый список с именем merged_list, который получится в результате объединения (сложения) списка list_a со списком list_b (в таком же порядке: сначала элементы list_a, затем list_b).
# В конце программы выведи список merged_list на экран.

list_a = [1, 2, 3]
list_b = [4, 5, 6]
merged_list = list_a + list_b
print(merged_list)


# Задача 7 Раздел: Замена элементов в списке

# Дан список:
# data = [10, 20, 30, 40, 50, 60]
# Замени в списке data сразу целый диапазон элементов с индекса 1 по индекс 3 (включительно) на новые значения: [21, 22, 23].
# В конце программы выведи измененный список data на экран.

data = [10, 20, 30, 40, 50, 60]
data[1:4] = [21,22,23]
print(data)


# Задача 8 Раздел: Создание списка / Добавление элементов в список

# Дан список:
# shopping = [] (пустой список)
# Создай пустой список с именем shopping (как указано выше).
# Поочередно добавь в него три строковых элемента: "bread", "milk", "eggs" (именно в таком порядке).
# В конце программы выведи готовый список shopping на экран.

shopping = []   # решение через вставку
shopping.insert(0, "bread")
shopping.insert(1, "milk")
shopping.insert(2,"eggs")
print(shopping)

shopping = []  # решение через append
shopping.append("bread")
shopping.append("milk")
shopping.append("eggs")
print(shopping)